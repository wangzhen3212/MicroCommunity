/**
 * 支付池值查询命令类
 * 
 * 该类负责处理支付池值的列表查询请求，包括参数验证和业务逻辑处理
 * 通过调用支付池值服务接口获取数据并返回分页结果
 * 
 * @author 吴学文
 * @version 1.0
 * @since 2023-10-25
 */
@Java110Cmd(serviceCode = "payment.listPaymentPoolValue")
public class ListPaymentPoolValueCmd extends Cmd {

    /**
     * 日志记录器
     */
    private static Logger logger = LoggerFactory.getLogger(ListPaymentPoolValueCmd.class);
    
    /**
     * 支付池值服务接口
     */
    @Autowired
    private IPaymentPoolValueV1InnerServiceSMO paymentPoolValueV1InnerServiceSMOImpl;

    /**
     * 参数验证方法
     * 
     * 验证请求参数的有效性，包括分页参数和必填字段
     * 
     * @param event 命令事件对象，包含请求相关信息
     * @param cmdDataFlowContext 命令数据流上下文，用于获取和设置请求响应数据
     * @param reqJson 请求参数的JSON对象
     * @throws CmdException 当参数验证失败时抛出异常
     */
    @Override
    public void validate(CmdEvent event, ICmdDataFlowContext cmdDataFlowContext, JSONObject reqJson) {
        // 验证分页参数
        super.validatePageInfo(reqJson);
        // 验证必填参数communityId是否存在且不为空
        Assert.hasKeyAndValue(reqJson, "communityId", "communityId不能为空");
    }

    /**
     * 命令执行方法
     * 
     * 处理支付池值查询业务逻辑，包括数据查询、分页处理和响应构建
     * 
     * @param event 命令事件对象
     * @param cmdDataFlowContext 命令数据流上下文
     * @param reqJson 请求参数的JSON对象
     * @throws CmdException 当业务逻辑处理过程中出现错误时抛出异常
     */
    @Override
    public void doCmd(CmdEvent event, ICmdDataFlowContext cmdDataFlowContext, JSONObject reqJson) throws CmdException {
        // 将请求JSON对象转换为支付池值数据传输对象
        PaymentPoolValueDto paymentPoolValueDto = BeanConvertUtil.covertBean(reqJson, PaymentPoolValueDto.class);

        // 查询支付池值记录总数
        int count = paymentPoolValueV1InnerServiceSMOImpl.queryPaymentPoolValuesCount(paymentPoolValueDto);

        List<PaymentPoolValueDto> paymentPoolValueDtos = null;

        // 根据查询结果数量决定返回数据
        if (count > 0) {
            // 如果存在记录，查询支付池值列表数据
            paymentPoolValueDtos = paymentPoolValueV1InnerServiceSMOImpl.queryPaymentPoolValues(paymentPoolValueDto);
        } else {
            // 如果没有记录，返回空列表
            paymentPoolValueDtos = new ArrayList<>();
        }

        // 计算总页数：总记录数除以每页显示行数，向上取整
        int totalPage = (int) Math.ceil((double) count / (double) reqJson.getInteger("row"));
        // 构建返回结果对象，包含总页数、总记录数和数据列表
        ResultVo resultVo = new ResultVo(totalPage, count, paymentPoolValueDtos);

        // 创建HTTP响应实体，设置响应状态为200 OK
        ResponseEntity<String> responseEntity = new ResponseEntity<String>(resultVo.toString(), HttpStatus.OK);

        // 将响应实体设置到数据流上下文中
        cmdDataFlowContext.setResponseEntity(responseEntity);
    }
}